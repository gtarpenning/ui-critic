#!/usr/bin/env python3
"""Rebuild taste/taste.md from the newest decisions with headless Claude. Text you wrote under "## My additions" is kept.

  distill.py [--max 40] [--model claude-sonnet-5-5] [--dry-run]
"""
import argparse, base64, json, mimetypes, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TASTE = os.path.join(ROOT, 'taste')
OUT = os.path.join(TASTE, 'taste.md')
MINE = '## My additions'
DEFAULT_MINE = 'Anything here survives rebuilds, and outranks the rules above.\n'


def img(rel):
    path = os.path.join(TASTE, rel)
    return {'type': 'image', 'source': {'type': 'base64', 'media_type': mimetypes.guess_type(path)[0],
                                        'data': base64.b64encode(open(path, 'rb').read()).decode()}}


def blocks(rows):
    out = []
    for r in rows:
        out += [{'type': 'text', 'text': f"Decision {r['id']} ({r['date']}). {r['context']}\nChosen:"}, img(r['winner']),
                {'type': 'text', 'text': 'Rejected:'}, img(r['loser']), {'type': 'text', 'text': f"Reason: {r['reason']}"}]
    return out


def claude(content, model):
    msg = json.dumps({'type': 'user', 'message': {'role': 'user', 'content': content}}) + '\n'
    env = {k: v for k, v in os.environ.items() if k != 'ANTHROPIC_API_KEY'}
    r = subprocess.run(['claude', '-p', '--model', model, '--input-format', 'stream-json', '--output-format', 'stream-json',
                        '--verbose', '--setting-sources', '', '--no-session-persistence', '--tools', ''],
                       input=msg, capture_output=True, text=True, timeout=600, env=env, cwd='/tmp')
    res = [json.loads(l) for l in r.stdout.splitlines() if l.startswith('{') and '"type":"result"' in l.replace(' ', '')]
    if not res or not res[-1].get('result'):
        sys.exit('claude returned nothing: ' + (r.stderr or r.stdout)[-500:])
    return res[-1]['result'], res[-1].get('total_cost_usd', 0)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--max', type=int, default=40)
    ap.add_argument('--model', default='claude-sonnet-5-5')
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()
    rows = [json.loads(l) for l in open(os.path.join(TASTE, 'decisions.jsonl')) if l.strip()]
    rows.sort(key=lambda r: r['date'])
    used = rows[-a.max:]
    if a.dry_run:
        print(f'would distill {len(used)} of {len(rows)} decisions')
        return
    prompt = open(os.path.join(ROOT, 'eval', 'prompts', 'distill.md')).read()
    text, cost = claude(blocks(used) + [{'type': 'text', 'text': prompt}], a.model)
    mine = DEFAULT_MINE
    if os.path.exists(OUT):
        parts = re.split(rf'^{re.escape(MINE)}\s*$', open(OUT).read(), maxsplit=1, flags=re.M)
        if len(parts) == 2 and parts[1].strip():
            mine = parts[1].strip() + '\n'
    with open(OUT, 'w') as f:
        f.write(f'# Taste\n\nGenerated by `scripts/distill.py` from {len(used)} decisions, newest {used[-1]["date"]}. '
                f'Decisions beat these rules, and newer beats older.\n\n{text.strip()}\n\n{MINE}\n\n{mine}')
    print(f'wrote {OUT} from {len(used)} decisions, ${cost:.2f}')


if __name__ == '__main__':
    main()
